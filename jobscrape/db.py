# --- liveness ---------------------------------------------------------------

def liveness_candidates(
    conn: Connection, sources: Iterable[str], limit: int = 500
) -> list[dict[str, Any]]:
    """Open postings from sources the fetch sweep can never close.

    Oldest-touched first, so a bounded run works through the backlog rather
    than re-probing the same head of the list every time.
    """
    names = list(sources)
    if not names:
        # `IN ()` is a syntax error, and an unbounded query here would probe
        # the entire catalogue. Refuse rather than guess.
        return []
    placeholders = ",".join("?" * len(names))
    return conn.execute(
        f"SELECT id, source, job_url, liveness_strikes FROM jobs "
        f"WHERE closed_at IS NULL AND duplicate_of IS NULL "
        f"AND source IN ({placeholders}) AND job_url <> '' "
        f"ORDER BY last_seen_at ASC LIMIT ?",
        (*names, limit),
    ).fetchall()


def record_liveness(conn: Connection, job_id: int, strikes: int, close: bool) -> None:
    """Persist a probe's outcome.

    Closing and the strike count are written together so a crash cannot leave a
    posting at the threshold but still open.
    """
    if close:
        conn.execute(
            "UPDATE jobs SET liveness_strikes = ?, closed_at = ? WHERE id = ?",
            (strikes, now_iso(), job_id),
        )
    else:
        # Guarded so a healthy catalogue does not issue an UPDATE per open job.
        conn.execute(
            "UPDATE jobs SET liveness_strikes = ? "
            "WHERE id = ? AND liveness_strikes <> ?",
            (strikes, job_id, strikes),
        )


def clear_duplicate(conn: Connection, job_id: int) -> None:
    """Reverse a mis-cluster: the row returns to the queue with its triage intact."""
    conn.execute("UPDATE jobs SET duplicate_of = NULL WHERE id = ?", (job_id,))
    conn.commit()


def duplicate_count(conn: Connection) -> int:
    return conn.execute(
        "SELECT COUNT(*) c FROM jobs WHERE duplicate_of IS NOT NULL"
    ).fetchone()["c"]


def stats(conn: Connection) -> dict[str, Any]:
    out: dict[str, Any] = {}
    out["total_jobs"] = conn.execute(
        "SELECT COUNT(*) c FROM jobs WHERE duplicate_of IS NULL"
    ).fetchone()["c"]
    out["duplicates_collapsed"] = duplicate_count(conn)
    out["by_source"] = {
        r["source"]: r["c"]
        for r in conn.execute(
            "SELECT source, COUNT(*) c FROM jobs WHERE duplicate_of IS NULL "
            "GROUP BY source ORDER BY c DESC"
        )
    }
    out["companies_by_ats"] = {
        f"{r['ats']}/{r['status']}": r["c"]
        for r in conn.execute(
            "SELECT ats, status, COUNT(*) c FROM companies GROUP BY ats, status ORDER BY ats, c DESC"
        )
    }
    row = conn.execute(
        "SELECT MIN(posted_at::date) lo, MAX(posted_at::date) hi FROM jobs "
        "WHERE posted_at IS NOT NULL AND duplicate_of IS NULL"
    ).fetchone()
    out["date_range"] = [
        row["lo"].isoformat() if row["lo"] else None,
        row["hi"].isoformat() if row["hi"] else None,
    ]
    out["top_companies"] = {
        r["company"]: r["c"]
        for r in conn.execute(
            "SELECT company, COUNT(*) c FROM jobs WHERE duplicate_of IS NULL "
            "GROUP BY company ORDER BY c DESC LIMIT 15"
        )
    }
    out["top_states"] = {
        r["state"]: r["c"]
        for r in conn.execute(
            "SELECT state, COUNT(*) c FROM jobs WHERE state IS NOT NULL AND duplicate_of IS NULL "
            "GROUP BY state ORDER BY c DESC LIMIT 15"
        )
    }
    return out
