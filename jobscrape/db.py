# --- the ?-placeholder compatibility shim ----------------------------------
#
# Every call site outside this module (cli.py, dashboard/*.py, tests) writes
# `conn.execute("... WHERE x = ?", (value,))` — the DBAPI/sqlite3 idiom. Rather
# than rewrite dozens of call sites to SQLAlchemy's native `:name` style, this
# module exposes a `Connection` that accepts the old style and translates it.
# Genuinely Postgres-only syntax (`::date` casts, `ON CONFLICT`, `RETURNING`)
# is written directly against `?` positions the same way — only the
# placeholder syntax is being adapted, not the SQL dialect.
#
# THE ONE TRAP: **every** `?` in the string becomes a bound parameter, including
# one inside a quoted literal and Postgres's own `?` operators. So these do not
# work through this Connection:
#
#     WHERE raw_json ? 'WorkplaceType'      -- JSONB key-exists operator
#     WHERE title ~ '^Eng(ineer)?$'         -- a `?` inside a regex literal
#     WHERE note = 'why?'                   -- a `?` inside any string literal
#
# The failure is loud rather than silent — SQLAlchemy raises "A value is
# required for bind parameter 'pN'" — but the message says nothing about the
# cause, which has cost real debugging time more than once. Workarounds:
# `jsonb_exists(raw_json, 'key')` for the JSONB operator, and passing any
# literal containing a `?` as a bound parameter instead of inlining it.

_QMARK_RE = re.compile(r"\?")


def _translate_sql(sql: str) -> str:
    counter = [0]

    def repl(_match: re.Match) -> str:
        counter[0] += 1
        return f":p{counter[0] - 1}"

    return _QMARK_RE.sub(repl, sql)


def _params_dict(params: Any) -> dict[str, Any]:
    if params is None:
        return {}
    if isinstance(params, dict):
        return params
    return {f"p{i}": v for i, v in enumerate(params)}


class _Result:
    """Adapts a SQLAlchemy CursorResult to the sqlite3.Cursor surface this
    codebase already uses: fetchone/fetchall/iteration returning dict-like
    rows indexable by column name, plus .rowcount and .lastrowid.
    """

    def __init__(self, result: Any) -> None:
        self._result = result
        self._rows: list[dict[str, Any]] | None = None
        # `.mappings()` consumes the underlying cursor, so it's read exactly
        # once here and cached — `scalar()` reads from this same cache rather
        # than re-touching `result` (which `fetchone`/`fetchall` empty out via
        # `self._rows`), or a `scalar()` call after any fetch would find the
        # cursor already exhausted and wrongly return None.
        self._first_row: dict[str, Any] | None = None
        if result is not None and result.returns_rows:
            self._rows = [dict(r) for r in result.mappings()]
            self._first_row = self._rows[0] if self._rows else None

    def fetchone(self) -> dict[str, Any] | None:
        if not self._rows:
            return None
        return self._rows.pop(0)

    def fetchall(self) -> list[dict[str, Any]]:
        if self._rows is None:
            return []
        rows, self._rows = self._rows, []
        return rows

    def __iter__(self) -> Iterator[dict[str, Any]]:
        return iter(self.fetchall())

    @property
    def rowcount(self) -> int:
        return self._result.rowcount if self._result is not None else 0

    def scalar(self) -> Any:
        if not self._first_row:
            return None
        return next(iter(self._first_row.values()))


class Connection:
    """Thin wrapper around a SQLAlchemy Core Connection.

    Deliberately not the ORM: every query here is explicit SQL, and this class
    exists only to keep the ``?``-placeholder call sites throughout the app
    working unchanged against Postgres. SQLAlchemy 2.0's ``Connection``
    auto-begins a transaction on first use, so the existing ``conn.commit()``
    calls sprinkled through the app carry over with their original meaning.
    """

    def __init__(self, sa_conn: Any) -> None:
        self._conn = sa_conn

    def execute(self, sql: str, params: Any = ()) -> _Result:
        translated = _translate_sql(sql)
        result = self._conn.execute(text(translated), _params_dict(params))
        return _Result(result)

    def executemany(self, sql: str, seq: Iterable[Any]) -> _Result:
        rows = [_params_dict(p) for p in seq]
        if not rows:
            return _Result(None)
        translated = _translate_sql(sql)
        result = self._conn.execute(text(translated), rows)
        return _Result(result)

    def commit(self) -> None:
        self._conn.commit()

    def rollback(self) -> None:
        self._conn.rollback()

    def close(self) -> None:
        self._conn.close()


_engines: dict[str, Engine] = {}


def _get_engine(database_url: str) -> Engine:
    """One pooled engine per URL, reused across connect() calls.

    A wide sweep runs ~16 concurrent async workers under a single asyncio
    lock, all reaching the same short-lived connections — a real pool (rather
    than one connection per call) is what makes that cheap.
    """
    engine = _engines.get(database_url)
    if engine is None:
        engine = create_engine(
            database_url,
            poolclass=QueuePool,
            pool_size=config.DB_POOL_SIZE,
            max_overflow=config.DB_MAX_OVERFLOW,
            pool_timeout=config.DB_POOL_TIMEOUT,
            echo=config.DB_ECHO,
            future=True,
        )
        _engines[database_url] = engine
    return engine


def _migrate(conn: Connection) -> None:
    # Postgres backfill of role_fingerprint/role_key for rows that predate
    # dedup is handled by `python -m jobscrape dedupe --backfill`, not here —
    # unlike the SQLite ALTER-COLUMN hook this replaces, adding a column is no
    # longer entangled with populating it.
    pass


def _strip_sql_comments(script: str) -> str:
    """Drop ``-- ...`` line comments before splitting on ``;``.

    A comment's own text may contain a semicolon ("boards paginate; a partial
    index keeps..."), which a naive split-then-strip would mistake for a
    statement boundary and chop the comment in two. Stripping comments from
    the whole script first, before any splitting, avoids that.
    """
    return "\n".join(
        line for line in script.splitlines() if not line.strip().startswith("--")
    )


def _apply_indexes(conn: Connection) -> None:
    for statement in filter(None, (s.strip() for s in _strip_sql_comments(INDEXES).split(";"))):
        conn.execute(statement)
    conn.commit()


def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


def connect(database_url: str | Path | None = None) -> Connection:
    """Open a connection. ``database_url`` overrides ``config.DATABASE_URL``.

    Accepts a bare string or ``Path`` for compatibility with older call sites
    that passed a SQLite file path; any such value is ignored in favour of
    ``config.DATABASE_URL`` unless it is itself a ``postgresql://`` URL, since
    a filesystem path is never a valid target now that storage is Postgres.
    """
    url = str(database_url) if database_url else None
    if url and "://" not in url:
        url = None
    engine = _get_engine(url or config.DATABASE_URL)
    sa_conn = engine.connect()
    conn = Connection(sa_conn)
    conn.execute(SCHEMA)
    conn.commit()
    _migrate(conn)
    _apply_indexes(conn)
    return conn


@contextmanager
def session(database_url: str | Path | None = None) -> Iterator[Connection]:
    conn = connect(database_url)
    try:
        yield conn
        conn.commit()
    finally:
        conn.close()


