# --- closure detection ------------------------------------------------------

def mark_board_closures(
    conn: Connection, source: str, company_slug: str | None, seen_ids: set[str]
) -> int:
    """Close postings absent from a **successful** fetch, after a grace period.

    The caller must only invoke this when the fetch genuinely succeeded. A
    failed or partial fetch returns no ids, and calling this on that basis would
    mark an entire company's jobs closed because of one network error.

    Closure is not immediate: a posting must have been unseen for
    ``config.CLOSURE_GRACE_HOURS`` (default 48h) before it is marked closed.
    Boards paginate inconsistently and truncate under load, and freehire's
    review of exactly this problem found that judging closure from one
    listing snapshot would have wrongly closed ~21k live Workday jobs.

    Pass ``company_slug=None`` for a global/aggregator source to skip per-company
    scoping entirely and treat that source's whole result set as one very large
    board. This is deliberately *not* the same as ``company_slug IS NULL``: jobs
    from global sources get a slug derived from their company name (see
    ``models.slugify``), so ``company_slug`` is rarely actually null even on
    adzuna or jooble rows — scoping on nullness there would close almost
    nothing.
    """
    if not seen_ids:
        return 0
    cutoff = (datetime.now(timezone.utc) - timedelta(hours=config.CLOSURE_GRACE_HOURS)).isoformat()
    slug_clause = "company_slug = ?" if company_slug is not None else "1=1"
    slug_param = [company_slug] if company_slug is not None else []
    # `= ANY(array)` rather than `NOT IN (?, ?, …)`: one bind parameter instead
    # of one per id. The old form hit PostgreSQL's 65,535-parameter ceiling on a
    # large global source — `seen_ids` is the RAW crawl result, not the filtered
    # `kept`, and Amazon alone runs 11 query terms against a 10,000-per-term cap.
    # Past the limit psycopg2 raises, the exception escapes `cmd_fetch`'s source
    # loop, `finish_run` never executes, and the `runs` row is left "running" —
    # which then blocks the dashboard from starting another fetch.
    #
    # Batching is not an option here: `NOT IN (A ∪ B)` is not `NOT IN A` then
    # `NOT IN B`, so a chunked version would close everything in the other chunk.
    result = conn.execute(
        f"UPDATE jobs SET closed_at = ? WHERE source = ? AND {slug_clause} "
        f"AND closed_at IS NULL AND last_seen_at < ? "
        f"AND NOT (source_job_id = ANY(?))",
        [now_iso(), source, *slug_param, cutoff, list(seen_ids)],
    )
    return result.rowcount


# --- job status (your triage) -----------------------------------------------

def set_job_status(
    conn: Connection,
    source: str,
    source_job_id: str,
    status: str,
    notes: str | None = None,
) -> None:
    if status not in JOB_STATUSES:
        raise ValueError(f"unknown status {status!r}; expected one of {JOB_STATUSES}")
    conn.execute(
        "INSERT INTO job_status (source, source_job_id, status, notes, updated_at) "
        "VALUES (?, ?, ?, ?, ?) "
        "ON CONFLICT(source, source_job_id) DO UPDATE SET "
        "status = excluded.status, "
        "notes = COALESCE(excluded.notes, job_status.notes), "
        "updated_at = excluded.updated_at",
        (source, source_job_id, status, notes, now_iso()),
    )
    conn.commit()


def status_counts(conn: Connection) -> dict[str, int]:
    counts = dict.fromkeys(JOB_STATUSES, 0)
    for row in conn.execute("SELECT status, COUNT(*) c FROM job_status GROUP BY status"):
        counts[row["status"]] = row["c"]
    # Anything never triaged is implicitly 'new'.
    total = conn.execute(
        "SELECT COUNT(*) c FROM jobs WHERE closed_at IS NULL AND duplicate_of IS NULL"
    ).fetchone()["c"]
    tracked = conn.execute("SELECT COUNT(*) c FROM job_status").fetchone()["c"]
    counts["new"] += max(total - tracked, 0)
    return counts


