def upsert_jobs(conn: Connection, jobs: Iterable[Job]) -> tuple[int, int]:
    """Insert or refresh jobs keyed on (source, source_job_id).

    Returns ``(inserted, updated)``. On conflict we refresh the mutable fields
    and bump ``last_seen_at`` but preserve the original ``first_seen_at`` so the
    archive keeps an accurate record of when we first observed a posting.
    ``COALESCE`` keeps previously captured detail when a later, shallower pass
    revisits the same posting with nulls. A re-upsert also clears `closed_at` —
    a posting the source is actively serving again is not closed, regardless
    of what an earlier sweep concluded.
    """
    from . import fingerprint as fp, scam, skills, staleness

    stamp = now_iso()
    updatable = [c for c in JOB_COLUMNS if c not in ("source", "source_job_id")]
    # Descriptions are expensive to obtain; never overwrite a good one with NULL.
    preserve = {"description_text", "posted_at", "salary_min",
                "salary_max", "salary_currency", "raw_json",
                # SmartRecruiters carries this on the DETAIL payload, and a
                # posting already stored is refreshed from the listing alone —
                # so an unpreserved assignment would erase the industry off
                # every row on the very next sweep of its board. It describes
                # the employer, not the opening, so a stale value cannot be
                # wrong in the way a stale salary could.
                "industry"}
    #: Columns where a *value* means "I could not tell", so it must be treated
    #: like NULL rather than like an answer.
    #:
    #: `workplace_type` is derived at construction from the description, the
    #: source's own workplace field and the structured remote flag — all three of
    #: which a shallow refresh strips, and the first of which is COALESCE-
    #: preserved above. So a cheap re-check recomputed "unknown" from nothing and
    #: overwrote the verdict a deep pass had already established. Measured: 178
    #: Workday postings stored `remoteType: Hybrid` in their payload and read
    #: `unknown`, and migration 0006 had already fixed those same rows once
    #: before a later sweep ate them again.
    #:
    #: Same class of bug as `evergreen_text`, `scam_signals` and `skills`, each of
    #: which carries a guard further down this statement. This one is expressed
    #: as NULLIF because the sentinel is a value, not a NULL.
    unknown_is_not_an_answer = {"workplace_type": "unknown"}
    def _assign(c: str) -> str:
        if c in preserve:
            return f"{c}=COALESCE(excluded.{c}, jobs.{c})"
        if c in unknown_is_not_an_answer:
            sentinel = unknown_is_not_an_answer[c]
            return f"{c}=COALESCE(NULLIF(excluded.{c}, '{sentinel}'), jobs.{c})"
        return f"{c}=excluded.{c}"

    set_clause = ", ".join(_assign(c) for c in updatable)
    placeholders = ", ".join("?" * (len(JOB_COLUMNS) + 8))
    sql = (
        f"INSERT INTO jobs ({', '.join(JOB_COLUMNS)}, first_seen_at, last_seen_at, "
        f"role_fingerprint, role_key, content_hash, evergreen_text, scam_signals, skills) "
        f"VALUES ({placeholders}) "
        f"ON CONFLICT(source, source_job_id) DO UPDATE SET {set_clause}, "
        f"last_seen_at=excluded.last_seen_at, closed_at=NULL, "
        f"role_fingerprint=excluded.role_fingerprint, role_key=excluded.role_key, "
        f"content_hash=excluded.content_hash, "
        # evergreen_text is DERIVED from description_text, which is COALESCEd
        # above — so it must follow the same rule. Assigning it unconditionally
        # would let a shallow refresh (which carries no description) recompute
        # it as false and wipe the flag off a posting whose description is
        # still there, preserved, one column over.
        f"evergreen_text=CASE WHEN excluded.description_text IS NOT NULL "
        f"THEN excluded.evergreen_text ELSE jobs.evergreen_text END, "
        # Same rule, same reason: a shallow refresh carries no description, and
        # recomputing from nothing would clear the flag off a posting whose
        # description is still stored one column over.
        f"scam_signals=CASE WHEN excluded.description_text IS NOT NULL "
        f"THEN excluded.scam_signals ELSE jobs.scam_signals END, "
        # And again for skills — the most consequential of the three, because
        # it is the one a user actually reads. A repeat sweep sends a shallow
        # refresh for every already-known posting, so without this guard the
        # column would be emptied on the second run of every board and the
        # damage would look like "skills extraction is broken" rather than
        # "the upsert overwrote it".
        f"skills=CASE WHEN excluded.description_text IS NOT NULL "
        f"THEN excluded.skills ELSE jobs.skills END, "
        # A reopen clears accumulated liveness strikes, so the two-strike grace
        # survives it. Without this a posting that was closed, came back, and
        # then returned one transient death signal would close again instantly
        # — the grace would apply only to its first life.
        f"liveness_strikes=CASE WHEN jobs.closed_at IS NOT NULL "
        f"THEN 0 ELSE jobs.liveness_strikes END"
    )

    inserted = updated = 0
    for job in jobs:
        row = job.to_row()
        values = (
            [row.get(c) for c in JOB_COLUMNS]
            + [stamp, stamp, fp.role_fingerprint(job), fp.role_key(job), fp.content_hash(job),
               staleness.has_evergreen_text(job.description_text),
               ",".join(scam.scam_signals(job.description_text)),
               skills.to_field(job.description_text)]
        )
        exists = conn.execute(
            "SELECT 1 FROM jobs WHERE source=? AND source_job_id=?",
            (job.source, job.source_job_id),
        ).fetchone()
        conn.execute(sql, values)
        if exists:
            updated += 1
        else:
            inserted += 1
    conn.commit()
    return inserted, updated


def known_job_ids(conn: Connection, source: str, company_slug: str) -> set[str]:
    """Ids already stored for one board."""
    return {
        row["source_job_id"]
        for row in conn.execute(
            "SELECT source_job_id FROM jobs WHERE source = ? AND company_slug = ?",
            (source, company_slug),
        )
    }


def record_rejected(
    conn: Connection,
    source: str,
    company_slug: str,
    rejected: Iterable[tuple[str, str | None]],
    reason: str = "rejected",
) -> None:
    """Remember postings whose detail we fetched and then discarded.

    Each entry is ``(source_job_id, posted_at)``. Storing the date means a later
    run with a wider window can decide locally whether to look again, instead of
    paying for the request to find out. ``reason`` distinguishes a real filter
    rejection from a cheap-prefilter skip — see the `posting_seen` schema.
    """
    stamp = now_iso()
    rows = [(source, jid, company_slug, posted, stamp, reason) for jid, posted in rejected]
    if not rows:
        return
    conn.executemany(
        "INSERT INTO posting_seen (source, source_job_id, company_slug, posted_at, evaluated_at, reason) "
        "VALUES (?, ?, ?, ?, ?, ?) "
        "ON CONFLICT(source, source_job_id) DO UPDATE SET evaluated_at = excluded.evaluated_at, "
        "reason = excluded.reason",
        rows,
    )
    conn.commit()


def delete_jobs(conn: Connection, keys: list[tuple[str, str]]) -> tuple[int, int]:
    """Remove postings outright. Returns ``(deleted, duplicates_released)``.

    The only destructive operation in the project — everything else marks a row
    closed. Used by ``jobscrape purge`` when a stored posting no longer passes
    the role filter, where marking it closed would be a lie: the employer did
    not withdraw it, we changed our mind about wanting it.

    **Surviving duplicates are released first, before the delete.** ``jobs``
    carries ``duplicate_of BIGINT REFERENCES jobs(id)``, so deleting a canonical
    while a duplicate still points at it raises a foreign-key violation and
    takes the whole purge down with it. Measured on the real archive, 35 rows
    sat in exactly that position. Clearing the pointer first both avoids the
    error and is the behaviour you want anyway: a duplicate whose canonical is
    gone has to become visible again, or it stays suppressed by a row that no
    longer exists — invisible in every view, with nothing to indicate why.

    Re-run ``dedupe --backfill`` afterwards to re-cluster the released rows
    against a surviving canonical.

    **`job_status` is deliberately untouched.** That table is separate precisely
    so a re-fetch can never erase where you applied; an orphaned note costs a
    row and restores itself if the posting is ever re-admitted.
    """
    if not keys:
        return 0, 0

    deleted = released = 0
    for offset in range(0, len(keys), 500):
        batch = keys[offset:offset + 500]
        placeholders = ",".join("(?, ?)" for _ in batch)
        params: list[Any] = []
        for source, job_id in batch:
            params.extend([source, job_id])

        released += conn.execute(
            f"UPDATE jobs SET duplicate_of = NULL WHERE duplicate_of IN "
            f"(SELECT id FROM jobs WHERE (source, source_job_id) IN ({placeholders}))",
            list(params),
        ).rowcount
        deleted += conn.execute(
            f"DELETE FROM jobs WHERE (source, source_job_id) IN ({placeholders})",
            list(params),
        ).rowcount
    conn.commit()
    return deleted, released


def skippable_ids(
    conn: Connection,
    source: str,
    company_slug: str,
    since: Any = None,
    until: Any = None,
) -> set[str]:
    """Postings that need no detail request this run.

    Two groups qualify:

    * **Stored** jobs — we already have their description.
    * **Previously rejected** postings that would still be rejected. A posting
      turned away for its role or region will be turned away again, since those
      come from listing fields. One turned away for its date is only skipped
      while its recorded date remains outside the requested window — widen the
      window and it is re-evaluated rather than silently missed.

    Together these take request savings from ~48% to ~95% on a repeat sweep.
    """
    ids = known_job_ids(conn, source, company_slug)

    for row in conn.execute(
        "SELECT source_job_id, posted_at FROM posting_seen "
        "WHERE source = ? AND company_slug = ?",
        (source, company_slug),
    ):
        posted = row["posted_at"]
        if not posted:
            # Rejected on role/region, which listing data alone decides.
            ids.add(row["source_job_id"])
            continue
        day = str(posted)[:10]
        outside = (since and day < str(since)) or (until and day > str(until))
        if outside or (since is None and until is None):
            ids.add(row["source_job_id"])
    return ids


def query_jobs(
    conn: Connection,
    *,
    since: str | None = None,
    until: str | None = None,
    sources: list[str] | None = None,
    state: str | None = None,
    company: str | None = None,
    search: str | None = None,
    limit: int | None = None,
    include_duplicates: bool = False,
) -> list[dict[str, Any]]:
    sql = "SELECT * FROM jobs WHERE 1=1"
    params: list[Any] = []
    if not include_duplicates:
        sql += " AND duplicate_of IS NULL"
    if since:
        sql += " AND posted_at::date >= ?"
        params.append(since)
    if until:
        sql += " AND posted_at::date <= ?"
        params.append(until)
    if sources:
        sql += f" AND source IN ({','.join('?' * len(sources))})"
        params.extend(sources)
    if state:
        sql += " AND state = ?"
        params.append(state.upper())
    if company:
        sql += " AND company ILIKE ?"
        params.append(f"%{company}%")
    if search:
        sql += " AND (title ILIKE ? OR description_text ILIKE ?)"
        params.extend([f"%{search}%", f"%{search}%"])
    sql += " ORDER BY posted_at DESC NULLS LAST, id DESC"
    if limit:
        sql += f" LIMIT {int(limit)}"
    return conn.execute(sql, params).fetchall()


# --- companies --------------------------------------------------------------

def add_companies(conn: Connection, ats: str, slugs: Iterable[str]) -> int:
    """Insert any of ``slugs`` not already known for ``ats``; return how many
    were actually new.

    Measured via a before/after count rather than ``RETURNING`` on the insert:
    a raw-SQL ``executemany`` batch (this can be thousands of rows during
    discovery) doesn't run through SQLAlchemy's insertmanyvalues machinery,
    so psycopg2's own executemany silently discards any ``RETURNING`` output
    — count the delta instead, which needs no such support.
    """
    stamp = now_iso()
    rows = [(ats, slug, stamp) for slug in slugs]
    if not rows:
        return 0
    before = conn.execute(
        "SELECT COUNT(*) c FROM companies WHERE ats = ?", (ats,)
    ).fetchone()["c"]
    conn.executemany(
        "INSERT INTO companies (ats, slug, discovered_at) VALUES (?, ?, ?) "
        "ON CONFLICT (ats, slug) DO NOTHING",
        rows,
    )
    after = conn.execute(
        "SELECT COUNT(*) c FROM companies WHERE ats = ?", (ats,)
    ).fetchone()["c"]
    conn.commit()
    return after - before


def mark_company(
    conn: Connection,
    ats: str,
    slug: str,
    status: str,
    job_count: int = 0,
    name: str | None = None,
    extra: str | None = None,
) -> None:
    conn.execute(
        "UPDATE companies SET status=?, job_count=?, last_checked=?, "
        "name=COALESCE(?, name), extra=COALESCE(?, extra) WHERE ats=? AND slug=?",
        (status, job_count, now_iso(), name, extra, ats, slug),
    )


def get_companies(
    conn: Connection,
    ats: str | None = None,
    status: str | list[str] | None = None,
    limit: int | None = None,
    order: str = "yield",
) -> list[dict[str, Any]]:
    """Rows from `companies`, biggest boards first by default.

    ``order="random"`` exists because the default ordering is useless — and
    actively misleading — for unchecked rows. An unchecked board has
    `job_count = 0`, so `job_count DESC, slug` degenerates into alphabetical
    order, and any `limit` then takes the same slice of the alphabet on every
    single run. Two callers need a *representative* slice instead: `validate`
    measuring a live-rate from a sample, and `fetch` chipping away at a backlog
    of 26,390 unchecked boards a few hundred at a time.
    """
    sql = "SELECT * FROM companies WHERE 1=1"
    params: list[Any] = []
    if ats:
        sql += " AND ats = ?"
        params.append(ats)
    if isinstance(status, str):
        sql += " AND status = ?"
        params.append(status)
    elif status:
        sql += f" AND status IN ({','.join('?' * len(status))})"
        params.extend(status)
    sql += " ORDER BY random()" if order == "random" else " ORDER BY job_count DESC, slug"
    if limit:
        sql += f" LIMIT {int(limit)}"
    return conn.execute(sql, params).fetchall()


# --- board_health: backoff for boards that keep failing ---------------------
#
# A board that 429s or times out was previously just skipped for the sweep,
# with no memory of it — so a struggling board gets retried at full frequency
# forever, feeding it more of exactly the load it is failing under. Backoff
# only kicks in after repeated failures, so one transient timeout costs
# nothing: `6h * 2^(f-3)`, capped at 24h, none below 3 consecutive failures.
# Adapted from freehire's board_health design.

def mark_board_failure(conn: Connection, ats: str, slug: str) -> None:
    row = conn.execute(
        "SELECT consecutive_failures FROM companies WHERE ats=? AND slug=?",
        (ats, slug),
    ).fetchone()
    failures = (row["consecutive_failures"] if row else 0) + 1
    cooldown = None
    if failures >= 3:
        hours = min(6 * (2 ** (failures - 3)), 24)
        cooldown = (datetime.now(timezone.utc) + timedelta(hours=hours)).isoformat()
    conn.execute(
        "UPDATE companies SET consecutive_failures=?, cooldown_until=? WHERE ats=? AND slug=?",
        (failures, cooldown, ats, slug),
    )


def mark_board_success(conn: Connection, ats: str, slug: str) -> None:
    conn.execute(
        "UPDATE companies SET consecutive_failures=0, cooldown_until=NULL WHERE ats=? AND slug=?",
        (ats, slug),
    )


def clear_ats_cooldowns(conn: Connection, ats: str) -> int:
    """Clear every cooldown for one ATS. Returns how many were cleared.

    Used by the half-open probe: a whole platform going down puts each of its
    boards into an independent backoff, and each would then serve out up to 24
    hours on its own schedule even after the outage ended. One board proving
    the platform answers again is enough evidence to release all of them.
    """
    result = conn.execute(
        "UPDATE companies SET consecutive_failures = 0, cooldown_until = NULL "
        "WHERE ats = ? AND cooldown_until IS NOT NULL",
        (ats,),
    )
    return result.rowcount


def boards_in_cooldown(conn: Connection, ats: str) -> set[str]:
    return {
        row["slug"]
        for row in conn.execute(
            "SELECT slug FROM companies WHERE ats=? AND cooldown_until IS NOT NULL "
            "AND cooldown_until > ?",
            (ats, now_iso()),
        )
    }


# --- yield backoff: boards that answer, but never with a software job --------
#
# The sibling of board_health above, and deliberately a SEPARATE mechanism. That
# one backs off a board that is failing; this one backs off a board that is
# working perfectly and simply has nothing this archive wants.
#
# Paycom is the case that forced it. Its 5,135 discovered portals are car
# dealerships, clinics and municipalities — one sampled live board served 55
# postings, of which the role prefilter passed exactly 0 ("Corporate Staff
# Accountant", "Forklift Mechanic", "Industrial Dock/Door Install"). Every
# sweep spent roughly 10,000 requests there and stored nothing. Those requests
# are the budget that the 26,390-board validation backlog needs.
#
# Backoff, not exclusion: a dealership can hire a developer, and the platform is
# not the thing at fault. A board that yields again resets to full frequency.

#: Consecutive zero-yield sweeps before a board is slowed down at all. Three, so
#: a board that is merely between openings is never affected.
ZERO_YIELD_GRACE = 3

#: Ceiling on the quiet period. Two weeks is long enough to matter for 5,135
#: boards and short enough that a board which starts hiring engineers is picked
#: up in the same month.
ZERO_YIELD_MAX_HOURS = 24 * 14


def mark_board_yield(conn: Connection, ats: str, slug: str, kept: int) -> None:
    """Record whether this sweep of a board produced anything worth storing.

    `kept` is the count AFTER the role/region/date filters, which is the only
    number that matters here — a board serving 55 forklift-mechanic postings has
    yielded nothing, however healthy its HTTP.
    """
    if kept:
        conn.execute(
            "UPDATE companies SET zero_yield_streak=0, quiet_until=NULL "
            "WHERE ats=? AND slug=?",
            (ats, slug),
        )
        return
    row = conn.execute(
        "SELECT zero_yield_streak FROM companies WHERE ats=? AND slug=?", (ats, slug)
    ).fetchone()
    streak = ((row["zero_yield_streak"] if row else 0) or 0) + 1
    quiet = None
    if streak >= ZERO_YIELD_GRACE:
        hours = min(24 * (2 ** (streak - ZERO_YIELD_GRACE)), ZERO_YIELD_MAX_HOURS)
        quiet = (datetime.now(timezone.utc) + timedelta(hours=hours)).isoformat()
    conn.execute(
        "UPDATE companies SET zero_yield_streak=?, quiet_until=? WHERE ats=? AND slug=?",
        (streak, quiet, ats, slug),
    )


def quiet_boards(conn: Connection, ats: str) -> set[str]:
    """Slugs currently backed off for yielding nothing. See mark_board_yield."""
    return {
        row["slug"]
        for row in conn.execute(
            "SELECT slug FROM companies WHERE ats=? AND quiet_until IS NOT NULL "
            "AND quiet_until > ?",
            (ats, now_iso()),
        )
    }


